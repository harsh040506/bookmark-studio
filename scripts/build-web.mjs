// Builds the website / PWA into dist/web.
//
//   1. Vite builds the app with relative asset URLs (works at a domain root, under a GitHub
//      Pages sub-path, or behind the local server).
//   2. A service worker is written with the exact list of files to precache, so the app opens
//      offline after the first visit. Hashed assets are cache-first (they never change); the
//      page itself is network-first, falling back to the cached copy when offline.
//   3. The public pages, Markdown copies, llms.txt, sitemap and robots.txt (build-site.mjs).
//      They are left out of the offline cache: only the app needs to open offline.
//   4. `.nojekyll` stops GitHub Pages from hiding files that start with an underscore.
import { readdirSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { build } from "vite";
import { buildSite } from "./build-site.mjs";

const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "dist", "web");

await build({ root: ROOT, mode: "web", logLevel: "info" });
const site = buildSite(OUT);
const notApp = new Set(site.written);

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

const files = walk(OUT)
  .map((file) => path.relative(OUT, file).split(path.sep).join("/"))
  .filter((file) => !file.endsWith(".map") && file !== "sw.js" && !notApp.has(file))
  // Social images, page media and the extension download are for other pages, not the app.
  .filter((file) => !/^(og|media)\//.test(file) && !file.endsWith(".zip"));

const version = `${Date.now().toString(36)}-${files.length}`;
const sw = `// Generated by scripts/build-web.mjs. Caches the app shell so the library opens offline.
const CACHE = "bookmark-studio-${version}";
const PRECACHE = ${JSON.stringify(["./", ...files.filter((file) => file !== "index.html")], null, 0)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      // The previous version's cache is kept until the next deploy: a tab opened before this
      // update still asks for that version's files (a worker, say), which the host no longer has.
      .then((keys) => {
        const older = keys.filter((key) => key.startsWith("bookmark-studio-") && key !== CACHE).sort();
        return Promise.all(older.slice(0, -1).map((key) => caches.delete(key)));
      })
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  // Only this app's own files. The local server's /api/* and every other origin pass through.
  if (url.origin !== self.location.origin || url.pathname.includes("/api/")) return;

  if (request.mode === "navigate") {
    // Only the app itself is kept for offline use. The about and privacy pages, and the
    // "not found" page, go to the network like any website; caching them under the app's
    // address would open the wrong page offline.
    const scope = new URL(self.registration.scope).pathname;
    if (url.pathname !== scope && url.pathname !== scope + "index.html") return;
    event.respondWith(
      fetch(request)
        .then((response) => {
          // Never cache an error page as the app.
          if (response.ok && response.type === "basic") {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put("./", copy));
          }
          return response;
        })
        .catch(() => caches.match("./").then((cached) => cached || Response.error())),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => cached || fetch(request).then((response) => {
      if (response.ok && url.pathname.includes("/assets/")) {
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(request, copy));
      }
      return response;
    })),
  );
});
`;

writeFileSync(path.join(OUT, "sw.js"), sw);
writeFileSync(path.join(OUT, ".nojekyll"), "");
console.log(`[build-web] dist/web ready — ${files.length} app files cached offline, service worker ${version}, site ${site.siteUrl}`);
